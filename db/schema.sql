-- Target schema for PostgreSQL + PostGIS (next delivery).
-- Today persistence is in memory (saved to data/db.json) behind the Repository interface,
-- so migrating means implementing a PostgresRepository with these tables.

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE user_role       AS ENUM ('PRODUCER', 'BUYER');
CREATE TYPE buyer_type      AS ENUM ('CONSUMER', 'STORE', 'RESTAURANT');
CREATE TYPE harvest_status  AS ENUM ('PLANTED', 'GROWING', 'AVAILABLE', 'SOLD_OUT');
CREATE TYPE order_status    AS ENUM ('PENDING', 'CONFIRMED', 'DELIVERED', 'CANCELLED');

-- "user" is a reserved word in PostgreSQL, hence app_user
CREATE TABLE app_user (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  role        user_role NOT NULL,
  name        TEXT NOT NULL,
  phone       TEXT,
  location    GEOGRAPHY(POINT, 4326),                 -- farm or delivery point (optional at sign-up)
  -- producer fields
  farm        TEXT,
  village     TEXT,
  town        TEXT,
  crops       TEXT[] DEFAULT '{}',
  -- buyer fields
  buyer_type  buyer_type,
  version     INT NOT NULL DEFAULT 1,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (role <> 'BUYER' OR buyer_type IS NOT NULL)
);
-- Spatial index: makes "nearby producers" queries efficient
CREATE INDEX app_user_location_gix ON app_user USING GIST (location);

-- Credentials apart from the profile: the hash never travels with the user data
CREATE TABLE credential (
  email    TEXT PRIMARY KEY,                          -- lowercase
  user_id  UUID NOT NULL UNIQUE REFERENCES app_user(id),
  salt     BYTEA NOT NULL,
  hash     BYTEA NOT NULL                             -- scrypt(password, salt, 64)
);

-- A producer's listing is stored as a harvest (status AVAILABLE when published)
CREATE TABLE harvest (
  id                  UUID PRIMARY KEY,               -- generated by the client (allows creating offline)
  producer_id         UUID NOT NULL REFERENCES app_user(id),
  product             TEXT NOT NULL,
  category            TEXT NOT NULL DEFAULT 'other',
  unit                TEXT NOT NULL DEFAULT 'kg',
  estimated_quantity  NUMERIC(10,2) NOT NULL CHECK (estimated_quantity > 0),
  reserved_quantity   NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
  unit_price          NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
  planted_on          DATE,
  available_on        DATE NOT NULL,
  description         TEXT DEFAULT '',
  photo               TEXT,
  status              harvest_status NOT NULL DEFAULT 'PLANTED',
  field_timestamps    JSONB NOT NULL DEFAULT '{}',    -- last write per field (LWW resolution)
  version             INT NOT NULL DEFAULT 1,
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (reserved_quantity <= estimated_quantity)
);
CREATE INDEX harvest_catalog_ix ON harvest (status, available_on);

-- "order" is a reserved word in PostgreSQL, hence purchase_order
CREATE TABLE purchase_order (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  harvest_id  UUID NOT NULL REFERENCES harvest(id),
  producer_id UUID NOT NULL REFERENCES app_user(id),
  buyer_id    UUID NOT NULL REFERENCES app_user(id),
  quantity    NUMERIC(10,2) NOT NULL CHECK (quantity > 0),
  unit_price  NUMERIC(12,2) NOT NULL,                 -- frozen when ordering
  status      order_status NOT NULL DEFAULT 'PENDING',
  version     INT NOT NULL DEFAULT 1,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Shopping cart: one row per product; the price is frozen in the order at checkout
CREATE TABLE cart_item (
  buyer_id    UUID NOT NULL REFERENCES app_user(id),
  harvest_id  UUID NOT NULL REFERENCES harvest(id) ON DELETE CASCADE,
  quantity    NUMERIC(10,2) NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (buyer_id, harvest_id)
);

CREATE TABLE rating (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id      UUID NOT NULL REFERENCES purchase_order(id),
  from_user_id  UUID NOT NULL REFERENCES app_user(id),
  to_user_id    UUID NOT NULL REFERENCES app_user(id),
  scores        JSONB NOT NULL,
  comment       TEXT DEFAULT '',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (order_id, from_user_id)                     -- one rating per party and per order
);

CREATE TABLE market_price (
  product          TEXT PRIMARY KEY,
  market_price     NUMERIC(12,2) NOT NULL,
  middleman_price  NUMERIC(12,2) NOT NULL,
  unit             TEXT NOT NULL,
  source           TEXT DEFAULT 'SIPSA-DANE',
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Idempotency of the offline synchronization
CREATE TABLE sync_operation (
  op_id         TEXT PRIMARY KEY,
  device_id     TEXT,
  result        JSONB NOT NULL,
  processed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

